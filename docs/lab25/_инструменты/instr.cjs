const fs = require('fs');
const path = require('path');
const DOCS = '/home/user/Fashion_site/docs/lab25';
const P = path.join(DOCS, '3_Прототип');

const folders = fs.readdirSync(P).filter((d) => fs.statSync(path.join(P, d)).isDirectory()).sort();
let total = 0;
const listing = folders.map((d) => {
  const files = fs.readdirSync(path.join(P, d)).filter((f) => f.endsWith('.svg')).sort();
  total += files.length;
  return `  ${d}/  (${files.length})\n` + files.map((f) => {
    const svg = fs.readFileSync(path.join(P, d, f), 'utf8').slice(0, 200);
    const h = (svg.match(/height="(\d+)"/) || [])[1];
    return `      ${f.replace('.svg', '').padEnd(48)} 1920 × ${h}`;
  }).join('\n');
}).join('\n\n');
const fontSet = new Map();
const walkSvg = (d) => fs.readdirSync(d, { withFileTypes: true }).forEach((e) => {
  const f = path.join(d, e.name);
  if (e.isDirectory()) return walkSvg(f);
  if (!e.name.endsWith('.svg')) return;
  for (const m of fs.readFileSync(f, 'utf8').matchAll(/font-family="([^"]+)"/g)) fontSet.set(m[1], (fontSet.get(m[1]) || 0) + 1);
});
walkSvg(DOCS);
const fonts = [...fontSet.entries()].sort((a, b) => b[1] - a[1]).map(([f]) => f);
const transitions = fs.existsSync(path.join(__dirname, 'transitions.txt')) ? fs.readFileSync(path.join(__dirname, 'transitions.txt'), 'utf8') : '';
const nTr = (transitions.match(/\]→/g) || []).length;
const lp = path.join(DOCS, '6_Для_Figma', 'Переходы.json');
const nLinks = fs.existsSync(lp) ? JSON.parse(fs.readFileSync(lp, 'utf8')).links.length : 0;
const sizeMb = (dir) => {
  let s = 0;
  const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).forEach((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : (s += fs.statSync(path.join(d, e.name)).size)));
  walk(dir);
  return (s / 1048576).toFixed(0);
};

