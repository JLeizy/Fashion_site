const SHOE_CATEGORIES = new Set(['sneakers', 'boots', 'heels', 'loafers', 'sandals']);
const BAG_CATEGORIES = new Set(['totes', 'crossbody', 'backpacks', 'clutches', 'wallets', 'belts']);

export function composition(material, category) {
  const [ru, en] = COMPOSITION[material] || COMPOSITION.cotton;
  if (SHOE_CATEGORIES.has(category) && material !== 'mesh' && material !== 'rubber') {
    return [`Верх: ${ru.toLowerCase()}; подкладка: кожа; подошва: резина`, `Upper: ${en.toLowerCase()}; lining: leather; sole: rubber`];
  }
  if (BAG_CATEGORIES.has(category) && !['canvas', 'nylon'].includes(material)) {
    return [`${ru}; подкладка: хлопок; фурнитура: металл`, `${en}; lining: cotton; hardware: metal`];
  }
  return [ru, en];
}

// Уход
export function care(material, category) {
  if (category.startsWith('fragrance')) {
    return ['Хранить при комнатной температуре вдали от прямого солнечного света.', 'Store at room temperature away from direct sunlight.'];
  }
  if (['rings', 'chains', 'bracelets', 'earrings', 'pendants'].includes(category)) {
    if (material === 'silver925') {
      return ['Снимать перед душем и сном, чистить салфеткой для серебра, хранить отдельно в мешочке.', 'Remove before showering and sleeping, clean with a silver cloth, store separately in a pouch.'];
    }
    return ['Беречь от воды, парфюма и ударов; хранить в футляре.', 'Keep away from water, perfume and knocks; store in the case.'];
  }
  if (category === 'sunglasses') return ['Протирать салфеткой из микрофибры, хранить в футляре.', 'Clean with a microfibre cloth and keep in the case.'];
  if (SHOE_CATEGORIES.has(category)) {
    return material === 'suede'
      ? ['Чистить мягкой щёткой для замши, защищать спреем от влаги, хранить с колодками в пыльнике.', 'Brush with a suede brush, protect with a water repellent spray, store with shoe trees in the dust bag.']
      : ['Протирать мягкой тканью, использовать крем для кожи, хранить с колодками в пыльнике.', 'Wipe with a soft cloth, use leather cream, store with shoe trees in the dust bag.'];
  }
  if (BAG_CATEGORIES.has(category) || category === 'gloves') {
    return ['Протирать сухой мягкой тканью, беречь от влаги и косметики, хранить набитым в пыльнике.', 'Wipe with a dry soft cloth, avoid moisture and cosmetics, store stuffed in the dust bag.'];
  }
  if (['wool', 'cashmere', 'mohair', 'vicuna', 'tweed'].includes(material)) {
    return ['Ручная стирка в холодной воде или сухая чистка; сушить горизонтально, не отжимать.', 'Hand wash cold or dry clean; dry flat, do not wring.'];
  }
  if (['silk', 'velvet', 'viscose'].includes(material)) return ['Только сухая чистка. Гладить с изнанки при низкой температуре.', 'Dry clean only. Iron inside out on a low setting.'];
  if (material === 'leather' || material === 'suede') return ['Профессиональная чистка кожи. Хранить на широких плечиках вдали от солнца.', 'Professional leather cleaning. Store on wide hangers away from sunlight.'];
  if (['nylon', 'polyester', 'technical'].includes(material)) return ['Деликатная стирка при 30 °C, не гладить, не отбеливать.', 'Gentle wash at 30 °C, do not iron or bleach.'];
  return ['Деликатная стирка при 30 °C, не отбеливать, сушить в расправленном виде, гладить с изнанки.', 'Gentle wash at 30 °C, do not bleach, dry flat, iron inside out.'];
}

